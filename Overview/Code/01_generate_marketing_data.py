import os
from datetime import datetime, timedelta
import numpy as np
import pandas as pd
from google.colab import files

# Set seed for reproducible results
np.random.seed(42)

# Create data output folder in Colab
os.makedirs("data", exist_ok=True)

START_DATE = datetime(2025, 1, 1)
DAYS = 365
NUM_USERS = 10000

CHANNELS = ["Meta Ads", "Google Search", "LinkedIn Ads", "TikTok Ads", "Organic / Email"]
CAMPAIGNS = {
    "Meta Ads": ["NO_Prospecting_Broad", "NO_Retargeting_Catalog"],
    "Google Search": ["NO_Brand_Search", "NO_Generic_NonBrand"],
    "LinkedIn Ads": ["NO_B2B_DecisionMakers"],
    "TikTok Ads": ["NO_Video_Views_UGC"],
    "Organic / Email": ["Newsletter_Weekly", "Direct_Organic"]
}

# ---------------------------------------------------------
# 1. GENERATE AD SPEND TABLE
# ---------------------------------------------------------
print("Generating ad_spend table...")
ad_spend_records = []

channel_params = {
    "Meta Ads": {"base_spend": 2800, "cpc": 7.5, "ctr": 0.016},
    "Google Search": {"base_spend": 2200, "cpc": 14.0, "ctr": 0.045},
    "LinkedIn Ads": {"base_spend": 1400, "cpc": 42.0, "ctr": 0.008},
    "TikTok Ads": {"base_spend": 1000, "cpc": 4.5, "ctr": 0.012},
    "Organic / Email": {"base_spend": 0, "cpc": 0.0, "ctr": 0.0}
}

for day_offset in range(DAYS):
    current_date = START_DATE + timedelta(days=day_offset)
    seasonality = 1.0 + 0.35 * (day_offset / DAYS)

    for channel in CHANNELS:
        params = channel_params[channel]
        daily_spend = round(params["base_spend"] * seasonality * np.random.uniform(0.85, 1.15), 2)

        if daily_spend > 0:
            cpc = params["cpc"] * np.random.uniform(0.9, 1.1)
            clicks = int(daily_spend / cpc)
            ctr = params["ctr"] * np.random.uniform(0.9, 1.1)
            impressions = int(clicks / ctr) if ctr > 0 else 0
        else:
            clicks = int(np.random.poisson(120 * seasonality))
            impressions = clicks * 15

        ad_spend_records.append({
            "date": current_date.strftime("%Y-%m-%d"),
            "channel": channel,
            "spend_nok": daily_spend,
            "impressions": impressions,
            "clicks": clicks
        })

df_ad_spend = pd.DataFrame(ad_spend_records)
df_ad_spend.to_csv("data/ad_spend.csv", index=False)

# ---------------------------------------------------------
# 2. GENERATE TOUCHPOINTS & TRANSACTIONS TABLES
# ---------------------------------------------------------
print("Simulating user journeys and conversions...")
touchpoint_records = []
transaction_records = []

touchpoint_id_counter = 1
transaction_id_counter = 1

for user_idx in range(1, NUM_USERS + 1):
    user_id = f"USR_{user_idx:05d}"
    user_start_offset = np.random.randint(0, DAYS - 45)
    first_touch_date = START_DATE + timedelta(days=user_start_offset)

    path_length = np.random.choice([1, 2, 3, 4, 5], p=[0.40, 0.30, 0.15, 0.10, 0.05])
    current_time = first_touch_date + timedelta(hours=int(np.random.randint(8, 22)))

    first_channel = np.random.choice(
        ["Meta Ads", "Google Search", "LinkedIn Ads", "TikTok Ads"],
        p=[0.45, 0.25, 0.15, 0.15]
    )

    user_touchpoints = []
    for touch_idx in range(path_length):
        if touch_idx == 0:
            touch_channel = first_channel
        else:
            touch_channel = np.random.choice(
                ["Google Search", "Organic / Email", "Meta Ads"],
                p=[0.50, 0.35, 0.15]
            )
            current_time += timedelta(
                days=int(np.random.exponential(scale=3.0)),
                hours=int(np.random.randint(1, 12))
            )

        campaign = np.random.choice(CAMPAIGNS[touch_channel])
        session_duration = int(np.random.gamma(shape=2, scale=60))

        tp_row = {
            "touchpoint_id": f"TP_{touchpoint_id_counter:07d}",
            "user_id": user_id,
            "timestamp": current_time.strftime("%Y-%m-%d %H:%M:%S"),
            "channel": touch_channel,
            "campaign": campaign,
            "session_duration_sec": max(15, session_duration)
        }
        touchpoint_records.append(tp_row)
        user_touchpoints.append(tp_row)
        touchpoint_id_counter += 1

    # Conversion probability scales with touchpoints
    conversion_prob = 0.04 + (0.05 * path_length)
    if np.random.rand() < conversion_prob:
        last_touch = user_touchpoints[-1]
        conversion_time = datetime.strptime(last_touch["timestamp"], "%Y-%m-%d %H:%M:%S") + timedelta(minutes=int(np.random.randint(5, 120)))

        base_basket = 1800 if first_channel == "LinkedIn Ads" else 850
        gross_rev = round(float(np.random.lognormal(mean=np.log(base_basket), sigma=0.45)), 2)
        margin_pct = round(np.random.uniform(0.40, 0.65), 2)
        is_refunded = int(np.random.rand() < 0.05)

        transaction_records.append({
            "transaction_id": f"TX_{transaction_id_counter:06d}",
            "user_id": user_id,
            "timestamp": conversion_time.strftime("%Y-%m-%d %H:%M:%S"),
            "gross_revenue_nok": gross_rev,
            "margin_pct": margin_pct,
            "is_refunded": is_refunded
        })
        transaction_id_counter += 1

        # Repeat customer logic
        if np.random.rand() < 0.25 and not is_refunded:
            repeat_time = conversion_time + timedelta(days=int(np.random.randint(14, 90)))
            if repeat_time <= (START_DATE + timedelta(days=DAYS)):
                repeat_rev = round(float(np.random.lognormal(mean=np.log(base_basket * 0.9), sigma=0.35)), 2)

                touchpoint_records.append({
                    "touchpoint_id": f"TP_{touchpoint_id_counter:07d}",
                    "user_id": user_id,
                    "timestamp": (repeat_time - timedelta(minutes=20)).strftime("%Y-%m-%d %H:%M:%S"),
                    "channel": "Organic / Email",
                    "campaign": "Newsletter_Weekly",
                    "session_duration_sec": int(np.random.randint(60, 300))
                })
                touchpoint_id_counter += 1

                transaction_records.append({
                    "transaction_id": f"TX_{transaction_id_counter:06d}",
                    "user_id": user_id,
                    "timestamp": repeat_time.strftime("%Y-%m-%d %H:%M:%S"),
                    "gross_revenue_nok": repeat_rev,
                    "margin_pct": margin_pct,
                    "is_refunded": 0
                })
                transaction_id_counter += 1

df_touchpoints = pd.DataFrame(touchpoint_records)
df_transactions = pd.DataFrame(transaction_records)

df_touchpoints.to_csv("data/touchpoints.csv", index=False)
df_transactions.to_csv("data/transactions.csv", index=False)

print("\n--- Summary ---")
print(f"ad_spend.csv:     {len(df_ad_spend):,} rows")
print(f"touchpoints.csv:  {len(df_touchpoints):,} rows")
print(f"transactions.csv: {len(df_transactions):,} rows")

# Quick look at touchpoint distribution by channel
print("Touchpoints per channel:")
print(df_touchpoints["channel"].value_counts())

print("\nTotal Media Spend (NOK):", f"{df_ad_spend['spend_nok'].sum():,.2f}")
print("Total Gross Revenue (NOK):", f"{df_transactions['gross_revenue_nok'].sum():,.2f}")

