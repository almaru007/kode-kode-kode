df_attributed.to_csv("Data/attributed_touchpoints.csv", index=False)
df_model_comparison.to_csv("Data/attribution_roas_comparison.csv", index=False)
cohort_summary.to_csv("Data/cohort_ltv_analysis.csv", index=False)

