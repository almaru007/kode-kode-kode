import os
import pandas as pd
import numpy as np

# Detect whether folder is Data or data
DATA_DIR = "Data" if os.path.exists("Data") else "data"
if not os.path.exists(DATA_DIR):
    DATA_DIR = "."  # fallback to root if files are in working dir

# Load Week 1 datasets
df_spend = pd.read_csv(os.path.join(DATA_DIR, "ad_spend.csv"))
df_touchpoints = pd.read_csv(os.path.join(DATA_DIR, "touchpoints.csv"))
df_transactions = pd.read_csv(os.path.join(DATA_DIR, "transactions.csv"))

# Parse timestamps
df_touchpoints["timestamp"] = pd.to_datetime(df_touchpoints["timestamp"])
df_transactions["timestamp"] = pd.to_datetime(df_transactions["timestamp"])

# Filter out refunded orders for net attribution
df_tx_valid = df_transactions[df_transactions["is_refunded"] == 0].copy()
df_tx_valid["net_revenue_nok"] = df_tx_valid["gross_revenue_nok"]

print(f"Loaded {len(df_touchpoints):,} touchpoints and {len(df_tx_valid):,} valid transactions.")

# ---------------------------------------------------------
# 1. MULTI-TOUCH ATTRIBUTION (MTA) MODELING
# ---------------------------------------------------------
print("\nCalculating First-Touch, Last-Touch, and U-Shaped Attribution weights...")

attribution_rows = []

for _, tx in df_tx_valid.iterrows():
    tx_id = tx["transaction_id"]
    user_id = tx["user_id"]
    tx_time = tx["timestamp"]
    net_rev = tx["net_revenue_nok"]

    # Touchpoints before this transaction
    prior_touches = df_touchpoints[
        (df_touchpoints["user_id"] == user_id) &
        (df_touchpoints["timestamp"] <= tx_time)
    ].sort_values("timestamp")

    if prior_touches.empty:
        continue

    n_touches = len(prior_touches)

    # Weight assignment logic
    if n_touches == 1:
        first_w = [1.0]
        last_w = [1.0]
        u_shaped_w = [1.0]
    elif n_touches == 2:
        first_w = [1.0, 0.0]
        last_w = [0.0, 1.0]
        u_shaped_w = [0.5, 0.5]
    else:
        # First-Touch (100% first)
        first_w = [1.0] + [0.0] * (n_touches - 1)
        # Last-Touch (100% last)
        last_w = [0.0] * (n_touches - 1) + [1.0]
        # U-shaped: 40% First, 40% Last, 20% distributed across middle touches
        middle_weight = 0.20 / (n_touches - 2)
        u_shaped_w = [0.40] + [middle_weight] * (n_touches - 2) + [0.40]

    for idx, (_, tp) in enumerate(prior_touches.iterrows()):
        attribution_rows.append({
            "transaction_id": tx_id,
            "user_id": user_id,
            "touchpoint_id": tp["touchpoint_id"],
            "channel": tp["channel"],
            "campaign": tp["campaign"],
            "fta_revenue": round(net_rev * first_w[idx], 2),
            "lta_revenue": round(net_rev * last_w[idx], 2),
            "ushaped_revenue": round(net_rev * u_shaped_w[idx], 2)
        })

df_attributed = pd.DataFrame(attribution_rows)

# Aggregate revenue attributed to each channel by model
df_channel_rev = df_attributed.groupby("channel")[["fta_revenue", "lta_revenue", "ushaped_revenue"]].sum().reset_index()

# Total spend by channel
df_channel_spend = df_spend.groupby("channel")["spend_nok"].sum().reset_index()

# Merge spend with model-attributed revenue
df_model_comparison = pd.merge(df_channel_spend, df_channel_rev, on="channel", how="left").fillna(0)

# Calculate Attributed ROAS for each model
df_model_comparison["roas_fta"] = round(df_model_comparison["fta_revenue"] / df_model_comparison["spend_nok"], 2).replace(np.inf, 0)
df_model_comparison["roas_lta"] = round(df_model_comparison["lta_revenue"] / df_model_comparison["spend_nok"], 2).replace(np.inf, 0)
df_model_comparison["roas_ushaped"] = round(df_model_comparison["ushaped_revenue"] / df_model_comparison["spend_nok"], 2).replace(np.inf, 0)

# ---------------------------------------------------------
# 2. COHORT RETENTION & NET LTV ENGINE
# ---------------------------------------------------------
print("Calculating Customer Cohorts & 90-Day LTV...")

# Determine customer's first purchase date
user_first_tx = df_tx_valid.groupby("user_id")["timestamp"].min().reset_index()
user_first_tx.columns = ["user_id", "first_tx_time"]
user_first_tx["cohort_month"] = user_first_tx["first_tx_time"].dt.to_period("M").astype(str)

# Map first touchpoint acquisition channel
user_first_touch = df_touchpoints.sort_values("timestamp").groupby("user_id").first().reset_index()[["user_id", "channel"]]
user_first_touch.columns = ["user_id", "acquisition_channel"]

user_profile = pd.merge(user_first_tx, user_first_touch, on="user_id", how="left")

# Merge cohort information back onto all valid transactions
df_cohort_tx = pd.merge(df_tx_valid, user_profile, on="user_id", how="left")
df_cohort_tx["days_since_first_tx"] = (df_cohort_tx["timestamp"] - df_cohort_tx["first_tx_time"]).dt.days

# Define maturation buckets
df_cohort_tx["maturation_window"] = pd.cut(
    df_cohort_tx["days_since_first_tx"],
    bins=[-1, 0, 30, 60, 90, 365],
    labels=["Day 0 (Initial)", "Day 1-30", "Day 31-60", "Day 61-90", "Day 90+"]
)

# Aggregate Cohort Table
cohort_summary = df_cohort_tx.groupby(["cohort_month", "acquisition_channel", "maturation_window"], observed=True).agg(
    active_users=("user_id", "nunique"),
    revenue_nok=("net_revenue_nok", "sum")
).reset_index()

